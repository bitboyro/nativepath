package ro.bitboy.nativepath.benchmarks;

import ro.bitboy.nativepath.NativePathHttpClient;
import ro.bitboy.nativepath.NativePathResponse;
import ro.bitboy.nativepath.NativePathStream;
import ro.bitboy.nativepath.NativeSecret;
import ro.bitboy.nativepath.internal.ForeignBridge;
import com.sun.net.httpserver.HttpServer;
import com.sun.net.httpserver.HttpsConfigurator;
import com.sun.net.httpserver.HttpsServer;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import org.openjdk.jmh.runner.Runner;
import org.openjdk.jmh.runner.options.Options;
import org.openjdk.jmh.runner.options.OptionsBuilder;
import org.springframework.web.client.RestClient;
import ro.bitboy.nativepath.spring.NativePathClientHttpRequestFactory;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;
import java.io.InputStream;
import java.io.OutputStream;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
import java.net.InetSocketAddress;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.util.Arrays;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

/**
 * Cost by layer. Each benchmark adds one layer on top of the previous, so the differences
 * between neighbouring rows are the cost of that layer:
 *
 *   ffiNoop            bare native call from Java
 *   ffiSynthetic       + Rust buffer alloc/fill/wipe, struct decode, NativeSecret, Cleaner (no network)
 *   ffiSyntheticHeap   + copy to a heap byte[]
 *   nativePathGet         real request: Rust HTTP engine + the above wrappers (no heap copy)
 *   nativePathGetHeap     + copy to a heap byte[]
 *   nativePathStreamRead  streaming API reading the whole body into a reused byte[]
 *   restNativePath        + Spring RestClient (converter, response wrappers)
 *   jdkHttpClient      baseline: java.net.http.HttpClient reading into a byte[]
 *
 * Concurrency: the server uses a thread pool, so {@code -t 8} measures 8 client threads sharing one
 * client rather than queueing behind a single server thread. TLS: {@code -p scheme=https} serves
 * over HttpsServer with a self-signed certificate generated by the JDK's keytool at setup.
 *
 * For the Rust-internal breakdown (headers / body / assemble / wipe) use the Rust-only run:
 * cargo run --release -p np-http-client --example rust_bench
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.MICROSECONDS)
@Warmup(iterations = 3, time = 2)
@Measurement(iterations = 5, time = 2)
@Fork(value = 2, jvmArgsAppend = "--enable-native-access=ALL-UNNAMED")
@State(Scope.Benchmark)
public class LayerBenchmark {

    @Param({"256", "8192", "65536", "524288"})
    public int payloadSize;

    @Param({"http"})
    public String scheme;

    private HttpServer server;
    private ExecutorService serverThreads;
    private String url;
    private NativePathHttpClient client;
    private NativePathClientHttpRequestFactory factory;
    private RestClient restNativePath;
    private NativePathHttpClient secretClient;
    private HttpClient jdkClient;

    @Setup(Level.Trial)
    public void setup() throws Exception {
        byte[] payload = new byte[payloadSize];
        Arrays.fill(payload, (byte) 'A');
        boolean tls = scheme.equals("https");
        SSLContext ssl = tls ? selfSignedContext() : null;
        InetSocketAddress addr = new InetSocketAddress("127.0.0.1", 0);
        if (tls) {
            HttpsServer https = HttpsServer.create(addr, 0);
            https.setHttpsConfigurator(new HttpsConfigurator(ssl));
            server = https;
        } else {
            server = HttpServer.create(addr, 0);
        }
        server.createContext("/api/payload", exchange -> {
            exchange.sendResponseHeaders(200, payload.length);
            try (OutputStream os = exchange.getResponseBody()) {
                os.write(payload);
            }
        });
        serverThreads = Executors.newCachedThreadPool();
        server.setExecutor(serverThreads);
        server.start();
        url = scheme + "://127.0.0.1:" + server.getAddress().getPort() + "/api/payload";
        client = NativePathHttpClient.builder().trustSelfSigned(tls).build();
        factory = NativePathClientHttpRequestFactory.builder().trustSelfSigned(tls).build();
        restNativePath = RestClient.builder().requestFactory(factory).build();
        secretClient = NativePathHttpClient.builder().secretMode(true).trustSelfSigned(tls).build();
        HttpClient.Builder jdk = HttpClient.newBuilder().version(HttpClient.Version.HTTP_1_1);
        if (tls) {
            jdk.sslContext(ssl);
        }
        jdkClient = jdk.build();
    }

    /** Key pair and certificate for 127.0.0.1 from keytool; the same context serves and trusts it. */
    private static SSLContext selfSignedContext() throws Exception {
        Path dir = Files.createTempDirectory("layerbench-tls");
        Path ks = dir.resolve("server.p12");
        char[] pass = "benchpass".toCharArray();
        Process p = new ProcessBuilder(
                Path.of(System.getProperty("java.home"), "bin", "keytool").toString(),
                "-genkeypair", "-alias", "bench", "-keyalg", "EC", "-groupname", "secp256r1",
                "-dname", "CN=127.0.0.1", "-ext", "SAN=ip:127.0.0.1", "-validity", "2",
                "-storetype", "PKCS12", "-keystore", ks.toString(),
                "-storepass", "benchpass", "-keypass", "benchpass")
                .redirectErrorStream(true).start();
        byte[] log = p.getInputStream().readAllBytes();
        if (p.waitFor() != 0) {
            throw new IllegalStateException("keytool failed: " + new String(log));
        }
        KeyStore store = KeyStore.getInstance("PKCS12");
        try (InputStream in = Files.newInputStream(ks)) {
            store.load(in, pass);
        }
        Files.delete(ks);
        Files.delete(dir);
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(store, pass);
        TrustManagerFactory tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        tmf.init(store);
        SSLContext ctx = SSLContext.getInstance("TLS");
        ctx.init(kmf.getKeyManagers(), tmf.getTrustManagers(), null);
        return ctx;
    }

    @TearDown(Level.Trial)
    public void tearDown() {
        factory.close();
        client.close();
        secretClient.close();
        jdkClient.close();
        server.stop(0);
        serverThreads.shutdownNow();
    }

    @Benchmark
    public void jdkHttpClient(Blackhole bh) throws Exception {
        HttpRequest req = HttpRequest.newBuilder(URI.create(url)).build();
        bh.consume(jdkClient.send(req, HttpResponse.BodyHandlers.ofByteArray()).body());
    }

    @Benchmark
    public void ffiNoop() {
        ForeignBridge.testNoop();
    }

    @Benchmark
    public void ffiSynthetic(Blackhole bh) {
        try (NativeSecret secret = decodeSynthetic()) {
            bh.consume(secret.length());
        }
    }

    @Benchmark
    public void ffiSyntheticHeap(Blackhole bh) {
        try (NativeSecret secret = decodeSynthetic()) {
            bh.consume(secret.toByteArray());
        }
    }

    @Benchmark
    public void nativePathGet(Blackhole bh) {
        try (NativePathResponse r = client.get(url)) {
            bh.consume(r.bodyAsSecret().length());
        }
    }

    @Benchmark
    public void nativePathGetHeap(Blackhole bh) {
        try (NativePathResponse r = client.get(url)) {
            bh.consume(r.bodyAsSecret().toByteArray());
        }
    }

    /** Pooled connection, chunks consumed in native memory only (no heap copy). */
    @Benchmark
    public void chunksPooled(Blackhole bh) {
        try (NativePathStream s = client.getStream(url)) {
            long total = 0;
            MemorySegment seg;
            while ((seg = s.nextChunk()) != null) total += seg.byteSize();
            bh.consume(total);
        }
    }

    /** Secret mode: same read, but a new connection per request and heap copies refused. */
    @Benchmark
    public void chunksSecretMode(Blackhole bh) {
        try (NativePathStream s = secretClient.getStream(url)) {
            long total = 0;
            MemorySegment seg;
            while ((seg = s.nextChunk()) != null) total += seg.byteSize();
            bh.consume(total);
        }
    }

    @Benchmark
    public void nativePathStreamRead(StreamBuf buf, Blackhole bh) throws Exception {
        try (NativePathStream s = client.getStream(url)) {
            long total = 0;
            int n;
            while ((n = s.read(buf.bytes, 0, buf.bytes.length)) > 0) total += n;
            bh.consume(total);
        }
    }

    @Benchmark
    public void restNativePath(Blackhole bh) {
        bh.consume(restNativePath.get().uri(url).retrieve().body(byte[].class));
    }

    @State(Scope.Thread)
    public static class StreamBuf {
        final byte[] bytes = new byte[64 * 1024];
    }

    /** Mirrors the decode in NativePathHttpClient.get for a synthetic, network-free response. */
    private NativeSecret decodeSynthetic() {
        MemorySegment raw = ForeignBridge.testResponse(payloadSize)
                .reinterpret(ForeignBridge.RESPONSE_LAYOUT.byteSize());
        MemorySegment bodyPtr = raw.get(ValueLayout.ADDRESS, 8);
        long len = raw.get(ValueLayout.JAVA_LONG, 16);
        long cap = raw.get(ValueLayout.JAVA_LONG, 24);
        NativeSecret secret = new NativeSecret(bodyPtr.address(), len, cap);
        ForeignBridge.responseShellFree(raw);
        return secret;
    }

    public static void main(String[] args) throws Exception {
        Options opts = new OptionsBuilder()
                .include(LayerBenchmark.class.getSimpleName())
                .addProfiler("gc")
                .build();
        new Runner(opts).run();
    }
}
